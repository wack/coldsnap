/**
 * Embeds files that bundled code needs at runtime as TypeScript modules:
 *
 * - tenant-template/ → lib/tenant-template/files.generated.ts, used by the
 *   eve agent and the deploy workflow.
 * - agent/skills/frontend-design/SKILL.md →
 *   agent/lib/frontend-design-skill.generated.ts, handed to Codex.
 *
 * Neither the Next.js functions nor the eve service can rely on reading the
 * repository from disk on Vercel; a module makes the bundler carry them.
 *
 *   node scripts/embed-assets.mjs          # regenerate
 *   node scripts/embed-assets.mjs --check  # fail if stale
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const templateDir = join(root, "tenant-template");
const templateOutput = join(root, "lib", "tenant-template", "files.generated.ts");
const skillSource = join(root, "agent", "skills", "frontend-design", "SKILL.md");
const skillOutput = join(root, "agent", "lib", "frontend-design-skill.generated.ts");

const SKIP = new Set(["node_modules", ".next", ".vercel", "package-lock.json", "next-env.d.ts"]);

function collect(dir) {
  const files = [];
  for (const entry of readdirSync(dir).sort()) {
    if (SKIP.has(entry) || entry.endsWith(".tsbuildinfo")) continue;
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) files.push(...collect(path));
    else files.push(path);
  }
  return files;
}

const files = collect(templateDir).map((path) => ({
  path: relative(templateDir, path).split(sep).join("/"),
  content: readFileSync(path, "utf8"),
}));

const templateModule = `// Generated by scripts/embed-assets.mjs from tenant-template/.
// Do not edit by hand: change the template, then run \`pnpm embed\`.

export interface TemplateFile {
  readonly path: string;
  readonly content: string;
}

export const TEMPLATE_FILES: readonly TemplateFile[] = ${JSON.stringify(files, null, 2)};
`;

/** Splits `---` frontmatter from a SKILL.md and reads its description. */
function parseSkill(markdown) {
  const match = /^---\n([\s\S]*?)\n---\n?/.exec(markdown);
  if (!match) throw new Error("SKILL.md has no frontmatter.");
  const description = /^description:\s*(.+)$/m.exec(match[1])?.[1]?.trim();
  if (!description) throw new Error("SKILL.md frontmatter has no description.");
  return { description, content: markdown.slice(match[0].length).trim() + "\n" };
}

const skill = parseSkill(readFileSync(skillSource, "utf8"));
const skillModule = `// Generated by scripts/embed-assets.mjs from agent/skills/frontend-design/SKILL.md
// (installed with \`eve add @skills/anthropics/skills/frontend-design\`, Apache-2.0).
// Do not edit by hand: run \`pnpm embed\` after updating the skill.

/** The frontend-design skill, in the shape the Codex harness accepts. */
export const FRONTEND_DESIGN_SKILL = {
  name: "frontend-design",
  description: ${JSON.stringify(skill.description)},
  content: ${JSON.stringify(skill.content)},
} as const;
`;

const outputs = [
  [templateOutput, templateModule],
  [skillOutput, skillModule],
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(
    ([file, source]) => !existsSync(file) || readFileSync(file, "utf8") !== source,
  );
  if (stale.length > 0) {
    for (const [file] of stale) console.error(`${relative(root, file)} is stale.`);
    console.error("Run `pnpm embed`.");
    process.exit(1);
  }
  console.log(`Embedded modules are up to date (${files.length} template files, 1 skill).`);
} else {
  for (const [file, source] of outputs) {
    writeFileSync(file, source);
    console.log(`Wrote ${relative(root, file)}.`);
  }
}
