/**
 * Embeds tenant-template/ into lib/tenant-template/files.generated.ts.
 *
 * The eve agent and the deploy workflow both need the template's files at
 * runtime, but neither bundle can rely on reading the repository from disk on
 * Vercel. Embedding them as a module makes the bundler carry them along.
 *
 *   node scripts/generate-template-module.mjs          # regenerate
 *   node scripts/generate-template-module.mjs --check  # fail if stale
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const templateDir = join(root, "tenant-template");
const outputFile = join(root, "lib", "tenant-template", "files.generated.ts");

const SKIP = new Set(["node_modules", ".next", ".vercel", "package-lock.json", "next-env.d.ts"]);

function collect(dir) {
  const files = [];
  for (const entry of readdirSync(dir).sort()) {
    if (SKIP.has(entry) || entry.endsWith(".tsbuildinfo")) continue;
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) files.push(...collect(path));
    else files.push(path);
  }
  return files;
}

const files = collect(templateDir).map((path) => ({
  path: relative(templateDir, path).split(sep).join("/"),
  content: readFileSync(path, "utf8"),
}));

const source = `// Generated by scripts/generate-template-module.mjs from tenant-template/.
// Do not edit by hand: change the template, then run \`pnpm template:generate\`.

export interface TemplateFile {
  readonly path: string;
  readonly content: string;
}

export const TEMPLATE_FILES: readonly TemplateFile[] = ${JSON.stringify(files, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(outputFile) ? readFileSync(outputFile, "utf8") : "";
  if (current !== source) {
    console.error("lib/tenant-template/files.generated.ts is stale. Run `pnpm template:generate`.");
    process.exit(1);
  }
  console.log(`Template module is up to date (${files.length} files).`);
} else {
  writeFileSync(outputFile, source);
  console.log(`Wrote ${relative(root, outputFile)} with ${files.length} files.`);
}
